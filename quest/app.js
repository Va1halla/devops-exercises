  // ---------- views ----------
  var view = { name: "home", filter: "all" };
  var session = null;

  function go(name, arg) {
    session = null;
    view.name = name;
    view.arg = arg;
    var hash = name === "topic" ? "t" + arg : name;
    if (location.hash.slice(1) !== hash) {
      try { history.replaceState(null, "", "#" + hash); } catch (e) { location.hash = hash; }
    }
    draw();
    window.scrollTo(0, 0);
  }
  function routeFromHash() {
    var h = location.hash.slice(1);
    var m = /^t(\d+)$/.exec(h);
    if (m && TOPICS[+m[1]]) { view.name = "topic"; view.arg = +m[1]; }
    else if (h === "achievements" || h === "profile") view.name = h;
    else view.name = "home";
  }

  function draw() {
    renderStatus();
    var main = $("#main");
    main.innerHTML = "";
    $("#tabs").hidden = !!session;
    document.querySelectorAll(".tab").forEach(function (b) {
      b.setAttribute("aria-current", b.dataset.go === view.name ? "page" : "false");
    });
    if (session) return drawSession(main);
    if (view.name === "topic") return drawTopic(main, TOPICS[view.arg]);
    if (view.name === "achievements") return drawAchievements(main);
    if (view.name === "profile") return drawProfile(main);
    drawHome(main);
  }

  function dueAll() {
    var now = Date.now();
    return Object.keys(S.cards).filter(function (id) { return CARD[id] && S.cards[id].d <= now; });
  }

