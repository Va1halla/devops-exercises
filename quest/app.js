  function nextBox(c, g) {
    var r = S.cards[c.id], b = r ? r.b : 0;
    if (g === "k") return Math.min(INTERVALS.length - 1, b + 1);
    if (g === "p") return Math.max(1, b);
    return 0;
  }
  function nextLabel(c, g) {
    var d = INTERVALS[nextBox(c, g)];
    return d + " " + plural(d, "день", "дня", "дней");
  }
  function reveal() { if (session && !session.shown) { session.shown = true; draw(); } }
  function grade(g) {
    if (!session || !session.shown) return;
    var c = session.cards[session.i];
    var r = S.cards[c.id];
    var isNew = !r;
    var box = nextBox(c, g);
    var now = Date.now();
    S.cards[c.id] = {
      b: box, d: g === "d" ? now + 10 * 60000 : now + INTERVALS[box] * DAY - 3600000,
      n: (r ? r.n : 0) + 1, k: (r ? r.k : 0) + (g === "k" ? 1 : 0), l: now
    };
    var xp;
    if (g === "k") {
      session.combo++;
      xp = Math.round(10 * (1 + Math.min(session.combo - 1, 10) * 0.1));
      S.knew++;
    } else {
      session.combo = 0;
      xp = g === "p" ? 4 : 1;
    }
    if (isNew) xp += 2;
    S.bestCombo = Math.max(S.bestCombo, session.combo);
    S.xp += xp;
    S.answers++;
    session.xp += xp;
    session.results[session.i] = g;
    session.i++;
    session.shown = false;
    markDay(1);
    if (session.i >= session.cards.length) finishSession();
    save();
    session.newAch = session.newAch.concat(checkAchievements());
    var lv = levelFor(S.xp).level;
    if (lv > (session.lastLevelToast || session.startLevel)) {
      session.lastLevelToast = lv;
      toast("Новый уровень", "Уровень " + lv, rankFor(lv).name);
    }
    draw();
    window.scrollTo(0, 0);
  }
  function finishSession() {
    S.sessions++;
    var knew = session.results.filter(function (x) { return x === "k"; }).length;
    if (session.cards.length >= SESSION_SIZE && knew === session.cards.length) S.perfect++;
    if (session.kind === "chaos") S.chaos++;
    if (session.kind === "boss") {
      session.bossWon = knew / session.cards.length >= BOSS_PASS;
      if (session.bossWon) {
        if (!S.bosses[session.topic.id]) { S.xp += 200; session.xp += 200; }
        S.bosses[session.topic.id] = Date.now();
      }
    }
    var tc = todayCount();
    session.sloHit = tc >= S.goal && tc - session.cards.length < S.goal;
  }
