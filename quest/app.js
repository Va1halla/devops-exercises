  // ---------- helpers ----------
  function $(sel, root) { return (root || document).querySelector(sel); }
  function el(tag, attrs, html) {
    var e = document.createElement(tag);
    if (attrs) Object.keys(attrs).forEach(function (k) {
      if (k === "class") e.className = attrs[k];
      else if (k.slice(0, 2) === "on") e.addEventListener(k.slice(2), attrs[k]);
      else e.setAttribute(k, attrs[k]);
    });
    if (html != null) e.innerHTML = html;
    return e;
  }
  function esc(s) {
    return String(s).replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }
  function today(ts) {
    var d = new Date(ts || Date.now());
    return d.getFullYear() + "-" + String(d.getMonth() + 1).padStart(2, "0") + "-" +
      String(d.getDate()).padStart(2, "0");
  }
  function plural(n, one, few, many) {
    var m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return one;
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
    return many;
  }
  function shuffle(a) {
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }
  function render(md) {
    var html = md;
    try {
      if (window.marked) html = window.marked.parse(md, { mangle: false, headerIds: false });
    } catch (e) { html = esc(md); }
    if (window.DOMPurify) html = window.DOMPurify.sanitize(html, { ADD_ATTR: ["target"] });
    return html;
  }
  function renderInline(md) {
    var html = md;
    try {
      if (window.marked) html = window.marked.parseInline(md);
    } catch (e) { html = esc(md); }
    if (window.DOMPurify) html = window.DOMPurify.sanitize(html);
    return html;
  }
  function monogram(title) {
    var w = title.replace(/\(.*?\)/g, "").trim().split(/[\s/-]+/).filter(Boolean);
    return (w.length > 1 ? w[0][0] + w[1][0] : title.slice(0, 2)).toUpperCase();
  }
  function iconHtml(t) {
    var mono = esc(monogram(t.title));
    if (!t.icon) return '<span class="ico" aria-hidden="true">' + mono + "</span>";
    return '<span class="ico" aria-hidden="true"><img src="' + esc(t.icon) + '" alt="" ' +
      'onerror="this.parentNode.textContent=\'' + mono + '\'"></span>';
  }

  // ---------- levels & ranks ----------
  function levelFor(xp) {
    // total XP to reach level L is 25*L*(L-1)
    var L = Math.floor((1 + Math.sqrt(1 + 4 * xp / 25)) / 2);
    var base = 25 * L * (L - 1), next = 25 * (L + 1) * L;
    return { level: L, into: xp - base, need: next - base };
  }
  function rankFor(level) {
    var name = RANKS[0][1], nextRank = null;
    for (var i = 0; i < RANKS.length; i++) {
      if (level >= RANKS[i][0]) name = RANKS[i][1];
      else { nextRank = RANKS[i]; break; }
    }
    return { name: name, next: nextRank };
  }

  // ---------- streak ----------
  function streak() {
    var n = 0, d = Date.now();
    if (!S.days[today(d)]) d -= DAY; // today not played yet: count up to yesterday
    while (S.days[today(d)]) { n++; d -= DAY; }
    return n;
  }
  function todayCount() { return S.days[today()] || 0; }

  // ---------- topic stats ----------
  function topicStats(t) {
    var seen = 0, mastered = 0, due = 0, now = Date.now();
    t.cards.forEach(function (c) {
      var r = S.cards[c.id];
      if (!r) return;
      seen++;
      if (r.b >= MASTER_BOX) mastered++;
      if (r.d <= now) due++;
    });
    var total = t.cards.length;
    var mastery = total ? mastered / total : 0;
    var questsDone = t.quests.filter(function (q) { return S.quests[q.e]; }).length;
    return {
      total: total, seen: seen, mastered: mastered, due: due, mastery: mastery,
      fresh: total - seen, quests: t.quests.length, questsDone: questsDone,
      level: total ? Math.min(5, Math.floor(mastery * 5 + (seen / total) * 0.999)) : 0
    };
  }
