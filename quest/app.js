  function startedTopics() {
    return TOPICS.filter(function (t) { return topicStats(t).seen > 0; }).length;
  }
  function masteredIn(id) {
    var t = TOPICS.filter(function (x) { return x.id === id; })[0];
    return t ? topicStats(t).mastered : 0;
  }
  function checkAchievements() {
    var fresh = [];
    ACH.forEach(function (a) {
      if (!S.ach[a[0]] && a[4]()) { S.ach[a[0]] = Date.now(); fresh.push(a); }
    });
    if (fresh.length) {
      save();
      fresh.forEach(function (a) { toast("Достижение", a[2], a[3]); });
    }
    return fresh;
  }

  // ---------- toasts ----------
  function toast(label, title, text) {
    var box = $("#toasts");
    var t = el("div", { class: "toast", role: "status" },
      '<span class="label">' + esc(label) + "</span><b>" + esc(title) + "</b>" +
      (text ? "<span>" + esc(text) + "</span>" : ""));
    box.appendChild(t);
    while (box.children.length > 3) box.firstChild.remove();
    setTimeout(function () { t.remove(); }, 4200);
  }

